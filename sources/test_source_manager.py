from global_sources import GLOBAL_SOURCES
from source_manager import fetch_all_sources


# ============================================================
# تشغيل الاختبار
# ============================================================

def main():

    print("===================================")
    print("     SOURCE MANAGER TEST")
    print("===================================")

    news = fetch_all_sources(
        GLOBAL_SOURCES
    )

    print()
    print("===================================")
    print(
        f"TOTAL NEWS: {len(news)}"
    )
    print("===================================")

    # --------------------------------------------------------
    # عرض أول 10 أخبار
    # --------------------------------------------------------

    for index, item in enumerate(
        news[:10],
        start=1
    ):

        print()
        print(
            f"{index}. "
            f"{item['title']}"
        )

        print(
            f"Source: "
            f"{item['source']}"
        )

        print(
            f"Category: "
            f"{item['category']}"
        )

        print(
            f"Priority: "
            f"{item['priority']}"
        )


# ============================================================
# تشغيل البرنامج
# ============================================================

if __name__ == "__main__":
    main()
