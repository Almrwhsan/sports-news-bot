# ============================================================
# أسماء التصنيفات
# ============================================================

CATEGORY_LABELS = {

    "real_madrid": "ريال مدريد",
    "barcelona": "برشلونة",
    "atletico_madrid": "أتلتيكو مدريد",

    "transfers": "سوق الانتقالات",

    "champions_league": "دوري أبطال أوروبا",

    "la_liga": "الدوري الإسباني",

    "premier_league": "الدوري الإنجليزي",

    "serie_a": "الدوري الإيطالي",

    "bundesliga": "الدوري الألماني",

    "ligue_1": "الدوري الفرنسي",

    "football": "كرة القدم",

    "world_football": "كرة القدم العالمية",
}


# ============================================================
# الحصول على اسم التصنيف
# ============================================================

def get_category_label(category):

    return CATEGORY_LABELS.get(
        category,
        "كرة القدم"
    )


# ============================================================
# تنظيف النص
# ============================================================

def clean_text(text):

    if not text:

        return ""

    return " ".join(
        str(text).split()
    ).strip()


# ============================================================
# بناء عنوان المنشور
# ============================================================

def build_post_title(news):

    title = clean_text(
        news.get(
            "arabic_title",
            news.get(
                "title",
                ""
            )
        )
    )

    return title


# ============================================================
# بناء نص المنشور
# ============================================================

def build_post_text(news):

    title = build_post_title(
        news
    )

    summary = clean_text(
        news.get(
            "arabic_summary",
            news.get(
                "summary",
                ""
            )
        )
    )

    category = get_category_label(
        news.get(
            "category",
            "football"
        )
    )

    source = clean_text(
        news.get(
            "source",
            ""
        )
    )

    lines = []

    # --------------------------------------------------------
    # العنوان
    # --------------------------------------------------------

    if title:

        lines.append(
            f"🚨 {title}"
        )

    # --------------------------------------------------------
    # الملخص
    # --------------------------------------------------------

    if summary:

        lines.append(
            ""
        )

        lines.append(
            f"📰 {summary}"
        )

    # --------------------------------------------------------
    # التصنيف
    # --------------------------------------------------------

    lines.append(
        ""
    )

    lines.append(
        f"🏷️ {category}"
    )

    # --------------------------------------------------------
    # المصدر
    # --------------------------------------------------------

    if source:

        lines.append(
            f"🌐 المصدر: {source}"
        )

    # --------------------------------------------------------
    # اسم الصفحة
    # --------------------------------------------------------

    lines.append(
        ""
    )

    lines.append(
        "📍 نبض مدريد"
    )

    return "\n".join(
        lines
    )


# ============================================================
# تنسيق خبر واحد
# ============================================================

def format_news_item(news):

    formatted_news = dict(
        news
    )

    formatted_news["post_title"] = (
        build_post_title(
            formatted_news
        )
    )

    formatted_news["post_text"] = (
        build_post_text(
            formatted_news
        )
    )

    return formatted_news


# ============================================================
# تنسيق مجموعة أخبار
# ============================================================

def format_news(news_list):

    formatted = []

    for news in news_list:

        formatted.append(
            format_news_item(
                news
            )
        )

    return formatted
